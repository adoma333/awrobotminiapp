export default function Guide() {
  const [q, setQ] = useState("");
  const [open, setOpen] = useState(null);
  const rows = useMemo(() => SECTIONS.map((s) => ({ ...s, items: s.items.filter(([t, b]) => !q || t.includes(q) || b.includes(q)) })).filter((s) => s.items.length), [q]);
  return (
    <>
      <div className="topbar"><h1>كيف تعمل لوحة التحكم</h1></div>
      <p className="muted" style={{ marginTop: -8 }}>دليل مختصر لكل قسم: ماذا يفعل ومتى تستخدمه. اضغط أي عنوان لقراءة التفاصيل.</p>
      <div className="filters"><input className="search" placeholder="ابحث في الدليل… (مثال: كوبون، تذكرة، نشر)" value={q} onChange={(e) => setQ(e.target.value)} /></div>
      {rows.map((s) => (
        <div key={s.g} className="panel guide-group">
          <h2>{s.g}</h2>
          {s.items.map(([title, body]) => {
            const k = `${s.g}-${title}`;
            const on = open === k || Boolean(q);
            return (
              <div key={k} className={`guide-item ${on ? "open" : ""}`}>
                <button type="button" onClick={() => setOpen(open === k ? null : k)}><span>{title}</span><i>{on ? "−" : "+"}</i></button>
                {on && <p>{body}</p>}
              </div>
            );
          })}
        </div>
      ))}
    </>
  );
}
